/* Copies the shared Optix theme into this product.
   Usage: node scripts/sync-theme.mjs [path-to-sdk]   (default ../optix-suite-sdk)  — run it again whenever the theme changes.
   Writes:
     site/optix-theme.css       the full theme (marketing pages: home, privacy, terms)
     site/consent.js            the AdSense consent loader (public pages only)
     assets/optix-tokens.css    only the design tokens + light/dark colours (the app, sign-up and platform pages, which have their own components)
   Do not edit the copies by hand; change them in optix-suite-sdk/theme and sync. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sdk = path.resolve(process.argv[2] || path.join(root, '..', 'optix-suite-sdk'));
const dir = path.join(sdk, 'theme');
const css = fs.readFileSync(path.join(dir, 'optix-theme.css'), 'utf8');
const cut = css.indexOf('*{box-sizing:border-box}');
if (cut < 0) throw new Error('optix-theme.css changed shape: cannot find the end of the token block');
fs.writeFileSync(path.join(root, 'site', 'optix-theme.css'), css);
fs.copyFileSync(path.join(dir, 'consent.js'), path.join(root, 'site', 'consent.js'));
fs.writeFileSync(path.join(root, 'assets', 'optix-tokens.css'), `/* Optix design tokens (colours, radius, shadows, type; light + dark). Generated by scripts/sync-theme.mjs from optix-suite-sdk/theme/optix-theme.css, do not edit. */\n${css.slice(css.indexOf(':root{'), cut).trimEnd()}\n`);
console.log(`site/optix-theme.css, site/consent.js and assets/optix-tokens.css written from ${dir}`);
