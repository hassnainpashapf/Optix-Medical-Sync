/* Copies the browser parts of @optix/suite-sdk (hub client + messaging) into ONE file the page can import: assets/optix-suite-sdk.js
   Usage: node scripts/sync-sdk.mjs [path-to-sdk]   (default ../optix-suite-sdk)  — run it again whenever the SDK changes. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sdk = path.resolve(process.argv[2] || path.join(root, '..', 'optix-suite-sdk'));
const pkg = JSON.parse(fs.readFileSync(path.join(sdk, 'package.json'), 'utf8'));
const body = ['client.js', 'messaging.js'].map((f) => fs.readFileSync(path.join(sdk, 'src', f), 'utf8').replace(/^import .*$/gm, '').trim()).join('\n\n');
const icons = fs.readFileSync(path.join(sdk, 'src', 'index.js'), 'utf8').match(/export const ICON_NAMES = .*$/m)[0];
fs.writeFileSync(path.join(root, 'assets', 'optix-suite-sdk.js'), `/* @optix/suite-sdk ${pkg.version} (browser build). Generated by scripts/sync-sdk.mjs — do not edit by hand. */\n${body}\n\n${icons}\n`);
console.log(`assets/optix-suite-sdk.js written from ${sdk} (v${pkg.version})`);
